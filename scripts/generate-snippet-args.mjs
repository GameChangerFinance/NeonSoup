#!/usr/bin/env node
import fs from 'node:fs/promises'
import path from 'node:path'

/**
 * Generates a JSON file to customize automatic frontend generation with 'gamechanger-cli'
 * This is usefull to automate basic frontend generation, specially for creating multi-intent dapps
 * The generated configuration JSON should be passed this way into the CLI tool:
 *   gamechanger-cli ... --snippetArgsFile snippet-args.json"
 *
 * Usage:
 *   node generate-snippet-args.js <output-json-file> <input-1.gcscript.json> [...more gcscript intents]
 *
 * Optional env with last-minute overrides:
 *   SNIPPET_ARGS='{"autoGeneratedLinkText":"Docs"}'
 */
export async function main({
  outputFile,
  inputFiles,
  snippetArgs = process.env.SNIPPET_ARGS
}) {
  if (!outputFile || inputFiles.length === 0) {
    throw new Error(
      'Usage: node generate-snippet-args.js <output-json-file> <input.gcscript.json> [...more]'
    )
  }

  const packageJson = JSON.parse(await fs.readFile('package.json', 'utf8'))
  const parsedSnippetArgs =
    typeof snippetArgs === 'string' && snippetArgs.trim()
      ? JSON.parse(snippetArgs)
      : {}

  const intents = Object.fromEntries(
    await Promise.all(
      inputFiles.map(async (file) => {
        const name = path.basename(file).replace(/\.gcscript(?:\.json)?$/i, '')
        const code = JSON.parse(await fs.readFile(file, 'utf8'))

        // The GC CLI/library expects defaultIntents entries to be script UI metadata. 
        // The actual GCScript must live under `code` property.
        return [
          name,
          {
            label: code.title || name,
            description: code.description || '',
            code
          }
        ]
      })
    )
  )

  const defaultIntents = JSON.stringify(intents)

  // Custom overrides, where we take some data from package.json to customize frontend
  const snippetArgsOverride = {
    appId: "gc-dapp-neon-soup",
    appVersion: packageJson.version,
    title: packageJson.name,
    description: packageJson.description
  }

  // Final JSON file design, where we apply layers with priorities
  // Last layers take precendent on merging
  const finalSnippetArgs = {
    defaultIntents,
    ...snippetArgsOverride,
    ...parsedSnippetArgs
  }
  
  // Create the output directory if does not exist
  await fs.mkdir(path.dirname(path.resolve(outputFile)), { recursive: true })
  // Writes/updates the JSON file
  await fs.writeFile(outputFile, JSON.stringify(finalSnippetArgs,null,2))
}

const [outputFile, ...inputFiles] = process.argv.slice(2)
main({ outputFile, inputFiles }).catch((err) => {
  console.error(err.message)
  process.exit(1)
})